"""Builds the README header (assets/header-{light,dark}.svg) and README.md from profile.toml.

Usage: pip install fonttools brotli && python tools/build.py
"""

from urllib.parse import urlparse

from lagoa import (
    ROOT, THEMES, Svg, birds, ghost, hill, hill_path, load_profile, mascot, meadow, measure, pine, river,
    round_tree, strip, swimmer, wrap,
)

W, H = 880, 470
PAD = 40


def short(url):
    u = urlparse(url)
    return (u.netloc.removeprefix("www.") + u.path).rstrip("/")


def header(theme, p):
    t = THEMES[theme]
    label = f"{p['name']}. {p['role']}. {p['headline']} {p['headline_italic']} {p['lead']}"
    s = Svg(W, H, theme, label, radius=24)

    # ---- landscape, back to front (the site footer, recomposed)
    s.add(f'<circle cx="790" cy="92" r="30" fill="{t["sun"]}"/>')
    ghost(s, 478, 372, p["name"].split()[0], 178, anchor="start")
    s.add(birds(600, 118, t, 1.2))
    far = hill(W, lambda x: 372 - max(0, x - 440) * 0.05, 9, 4, wl=(520, 300))
    s.add(hill_path(W, H, far, t["hill_far"]))
    mid = hill(W, lambda x: 404, 6, 8, wl=(460, 260))
    s.add(hill_path(W, H, mid, t["hill_mid"]))
    for x, sz in [(770, 96), (812, 150), (860, 116)]:
        s.add(pine(x, mid(x) + 10, sz, t))
    for x, sz in [(500, 96), (556, 60)]:
        s.add(round_tree(x, mid(x) + 8, sz, t))
    near = hill(W, lambda x: 440, 4, 12, wl=(400, 220))
    s.add(hill_path(W, H, near, t["hill_near"]))
    s.add(river(668, far(668) + 2, 18, 650, H, 250, t))
    s.add(meadow(0, 520, near, t, seed=2))
    s.add(meadow(790, W, near, t, seed=5))
    swimmer(s, 652, 436, 64)

    # ---- top bar: head mark + name, status on the right
    head, hw = mascot("head", PAD - 6, 26, 40)
    s.add(head)
    s.text(PAD + hw - 4, 52, p["name"], "serif", 24, t["ink"])
    right = W - PAD
    loc_w = measure(p["location"].upper(), "mono5", 10.5, 2.1)
    s.text(right, 50, p["location"], "mono5", 10.5, t["muted"], ls=2.1, anchor="end", upper=True)
    if p.get("available"):
        word = "Open to work"
        ww = measure(word.upper(), "mono5", 10.5, 2.1)
        sx = right - loc_w - 26 - ww
        s.add(f'<circle cx="{sx - 11:.1f}" cy="46" r="3.6" fill="{t["available"]}"/>')
        s.text(sx, 50, word, "mono5", 10.5, t["ink"], ls=2.1, upper=True)

    # ---- eyebrow, headline, lead
    s.text(PAD, 116, "  ·  ".join(p["tags"]), "mono5", 10.5, t["muted"], ls=2.1, upper=True)
    s.text(PAD - 3, 182, p["headline"], "serif", 72, t["ink"], ls=-1.4)
    s.text(PAD, 236, p["headline_italic"], "serif-i", 52, t["muted"])
    for i, line in enumerate(wrap(p["lead"], "sans", 15.5, 400)):
        s.text(PAD, 282 + i * 25, line, "sans", 15.5, t["muted"])

    # ---- quick-links strip floating over the ground
    strip(s, PAD, 384, [("Email", p["email"]), ("Website", short(p["site"]))])
    return s


def readme(p, projects):
    alt = f"{p['name']} · {p['role']}. {p['headline']} {p['headline_italic']} {p['lead']}"
    out = [
        "<!-- Generated by tools/build.py from profile.toml. Edit that file, not this one. -->",
        f'<a href="{p["site"]}"><picture><source media="(prefers-color-scheme: dark)" srcset="assets/header-dark.svg">'
        f'<img src="assets/header-light.svg" alt="{alt}" width="100%"></picture></a>',
        "",
    ]
    if projects:
        out += ["### Projects", "", "| | Project | Stack |", "| :-- | :-- | :-- |"]
        for i, pr in enumerate(projects, 1):
            name = f"**[{pr['name']}]({pr['url']})**" if pr.get("url") else f"**{pr['name']}**"
            if pr.get("status"):
                name += f" · <sub>{pr['status'].upper()}</sub>"
            out.append(f"| `{i:02d}` | {name}<br>{pr['description']} | `{pr['stack']}` |")
        out.append("")
    return "\n".join(out)


def main():
    data = load_profile()
    p, projects = data["profile"], data.get("projects", [])
    assets = ROOT / "assets"
    assets.mkdir(exist_ok=True)
    for theme in THEMES:
        (assets / f"header-{theme}.svg").write_text(header(theme, p).render(), encoding="utf-8")
    (ROOT / "README.md").write_text(readme(p, projects), encoding="utf-8")
    print(f"header + README com {len(projects)} projeto(s)")


if __name__ == "__main__":
    main()
